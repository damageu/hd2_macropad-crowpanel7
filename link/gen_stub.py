#!/usr/bin/env python3
"""Generate stub_esp32s3.h from esptool's ESP32-S3 flasher stub JSON.

Source: esptool 5.2.0 (pip), esptool/targets/stub_flasher/2/esp32s3.json,
built from https://github.com/espressif/esp-flasher-stub/releases/tag/v0.2.0
Licence of the stub binary: Apache-2.0 OR MIT (see third_party/esp-flasher-stub).
Usage: python3 gen_stub.py third_party/esp-flasher-stub/esp32s3.json > stub_esp32s3.h
"""
import base64, hashlib, json, sys

path = sys.argv[1]
raw = open(path, 'rb').read()
j = json.loads(raw)
text = base64.b64decode(j['text'])
data = base64.b64decode(j['data'])

def arr(name, b):
    out = [f'static const unsigned char {name}[{len(b)}] = {{']
    for i in range(0, len(b), 16):
        out.append('    ' + ', '.join(f'0x{x:02X}' for x in b[i:i + 16]) + ',')
    out.append('};')
    return '\n'.join(out)

print('/* Generated by gen_stub.py. Do not edit.')
print(' * ESP32-S3 flasher stub from esptool 5.2.0, stub_flasher/2/esp32s3.json')
print(' * (espressif/esp-flasher-stub v0.2.0).')
print(' * Copyright (c) 2025 Espressif Systems (Shanghai) CO LTD.')
print(' * Licensed under the Apache License 2.0 or the MIT licence, at your option.')
print(' * See third_party/esp-flasher-stub/LICENSE-MIT and LICENSE-APACHE.')
print(f' * JSON sha256: {hashlib.sha256(raw).hexdigest()}')
print(' */')
print('#ifndef HD2_STUB_ESP32S3_H')
print('#define HD2_STUB_ESP32S3_H')
print(f'#define STUB_S3_ENTRY      0x{j["entry"]:08X}u')
print(f'#define STUB_S3_TEXT_START 0x{j["text_start"]:08X}u')
print(f'#define STUB_S3_DATA_START 0x{j["data_start"]:08X}u')
print(f'#define STUB_S3_JSON_SHA256 "{hashlib.sha256(raw).hexdigest()}"')
print(arr('stub_s3_text', text))
print(arr('stub_s3_data', data))
print('#endif')
